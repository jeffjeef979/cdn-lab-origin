// Endpoint (b): custom code written for this lab.
// The HTML is dynamic (timestamp, visitor info) so it is never cached,
// but it embeds endpoint (c), /static/edge.png, which the CDN caches.
export default function handler(req, res) {
  const name = String(req.query.name || 'visitor').replace(/[^\w\s-]/g, '').slice(0, 40);
  const country = req.headers['x-vercel-ip-country'] || 'unknown';
  const viaCdn = req.headers['via'] ? 'yes (' + req.headers['via'] + ')' : 'no Via header seen';

  res.setHeader('Cache-Control', 'no-store');
  res.setHeader('Content-Type', 'text/html; charset=utf-8');
  res.status(200).send(`<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>CDN Lab - Hello</title>
  <style>
    body { font-family: system-ui, sans-serif; max-width: 640px; margin: 40px auto; padding: 0 16px; color: #1a1a2e; }
    code { background: #eef; padding: 2px 6px; border-radius: 4px; }
    img { max-width: 100%; border-radius: 8px; margin-top: 16px; }
    .meta { color: #555; font-size: 14px; }
  </style>
</head>
<body>
  <h1>Hello, ${name}!</h1>
  <p>This page is generated by a serverless function on the origin (never cached).</p>
  <p class="meta">Generated at: <code>${new Date().toISOString()}</code><br>
     Origin saw country: <code>${country}</code><br>
     Request came through a proxy/CDN: <code>${viaCdn}</code></p>
  <p>The image below is a static asset served from <code>/static/edge.png</code>, which the CDN caches:</p>
  <img src="/static/edge.png" alt="Test image cached at the CDN edge" width="600" height="300">
</body>
</html>`);
}
